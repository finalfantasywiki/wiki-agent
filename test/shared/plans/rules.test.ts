import { describe, test } from 'node:test';
import assert from 'node:assert/strict';
import { buildManifest, type Manifest, type ManifestInput } from '../../../src/shared/plans/manifest.ts';
import { applyRules } from '../../../src/shared/plans/rules.ts';
import type { OperatingRules } from '../../../src/shared/profile/profile.ts';

const ID = '3f1c2a64-8d0e-4c5b-9a7e-2b6d1f0c9e88';
const NOW = new Date('2026-11-02T12:00:00Z');

const NAMESPACES = new Set(['Category', 'File', 'Template']);
/** "Final Fantasy VII: Advent Children" is in main: its prefix isn't a namespace. */
const namespaceOf = (title: string) => {
  const prefix = title.split(':')[0] ?? '';
  return title.includes(':') && NAMESPACES.has(prefix) ? prefix : '';
};

const RULES: OperatingRules = { createPagesIn: ['Category'], forbiddenTemplates: ['bot-generated'] };

function edit(title: string, diff: string, from: string): ManifestInput['references']['edits'][number] {
  return { title, revid: 1, timestamp: '2026-11-01T00:00:00Z', text: '', diff, rewrites: [{ kind: 'category', from, before: '', after: '' }] };
}

function manifest(input: Partial<ManifestInput>): Manifest {
  return buildManifest(
    { wiki: 'example', api: 'https://wiki.test/api.php', references: { edits: [], usages: [], leftovers: [], blocked: [] }, ...input },
    { id: ID, now: NOW },
  );
}

/** Each entry's error codes, by ID. */
const errorsOf = (planned: Manifest) =>
  Object.fromEntries(planned.entries.flatMap((entry) => (entry.kind === 'question' ? [] : [[entry.id, entry.errors.map((error) => error.code)]])));

describe('applyRules', () => {
  test('changes nothing without rules', () => {
    const planned = manifest({ pageCreations: [{ title: 'Cloud Strife', text: '{{bot-generated}}', reason: 'r' }] });
    assert.equal(applyRules(planned, undefined, namespaceOf), planned);
    assert.equal(applyRules(planned, {}, namespaceOf), planned);
  });

  test('pages may only be created in the allowed namespaces', () => {
    const planned = applyRules(
      manifest({
        pageCreations: [
          { title: 'Category:Images of Cloud Strife', text: '{{category}}', reason: 'r' },
          { title: 'Final Fantasy VII: Advent Children', text: 'An article', reason: 'r' },
          { title: 'Template:New', text: '', reason: 'r' },
        ],
      }),
      RULES,
      namespaceOf,
    );
    assert.deepEqual(errorsOf(planned), { n1: [], n2: ['create-not-allowed'], n3: ['create-not-allowed'] });
    assert.equal(planned.entries[1]?.kind === 'page-create' && planned.entries[1].approved, false);
    assert.match(planned.entries[1]?.kind === 'page-create' ? planned.entries[1].errors[0]!.message : '', /only allows the bot to create pages in Category/);
  });

  test('"" allows the main namespace', () => {
    const planned = applyRules(manifest({ pageCreations: [{ title: 'Cloud Strife', text: '', reason: 'r' }] }), { createPagesIn: [''] }, namespaceOf);
    assert.deepEqual(errorsOf(planned), { n1: [] });
  });

  test("a category rename's new page counts as a creation", () => {
    const planned = applyRules(
      manifest({
        categories: [{ from: 'Category:Old', to: 'Category:New', create: { text: '{{Bot-generated |date=now}}', model: undefined }, old: undefined, members: [], errors: [], warnings: [] }],
      }),
      RULES,
      namespaceOf,
    );
    assert.deepEqual(errorsOf(planned), { c1: ['forbidden-template'] });
  });

  test('new pages and edits may not add a forbidden template, in any spelling', () => {
    for (const call of ['{{bot-generated}}', '{{ Bot-generated |x}}', '{{Template:bot-generated}}', '{{template : Bot-generated}}']) {
      const planned = applyRules(manifest({ pageCreations: [{ title: 'Category:X', text: `${call}\n`, reason: 'r' }] }), RULES, namespaceOf);
      assert.deepEqual(errorsOf(planned), { n1: ['forbidden-template'] }, call);
    }
    // Spaces and underscores are the same in a template's name.
    const spaced = applyRules(manifest({ pageCreations: [{ title: 'Category:X', text: '{{Generated_by bot}}', reason: 'r' }] }), { forbiddenTemplates: ['generated by bot'] }, namespaceOf);
    assert.deepEqual(errorsOf(spaced), { n1: ['forbidden-template'] });
    // Another template whose name starts the same is fine.
    const other = applyRules(manifest({ pageCreations: [{ title: 'Category:X', text: '{{bot-generated list}}', reason: 'r' }] }), RULES, namespaceOf);
    assert.deepEqual(errorsOf(other), { n1: [] });
  });

  test('an edit may keep a forbidden template, but not add one', () => {
    const planned = applyRules(
      manifest({
        categoryTags: [
          { title: 'Kept', category: 'Category:A' },
          { title: 'Added', category: 'Category:A' },
        ],
        references: {
          edits: [
            edit('Kept', '--- Kept\n+++ Kept\n-{{bot-generated}}\n-[[Category:Old]]\n+{{bot-generated}}\n+[[Category:A]]', 'Kept'),
            edit('Added', '--- Added\n+++ Added\n-[[Category:Old]]\n+{{bot-generated}}[[Category:A]]', 'Added'),
          ],
          usages: [],
          leftovers: [],
          blocked: [],
        },
      }),
      RULES,
      namespaceOf,
    );
    assert.deepEqual(errorsOf(planned), { t1: [], t2: ['forbidden-template'] });
  });
});
